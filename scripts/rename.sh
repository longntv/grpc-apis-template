#!/usr/bin/env bash
# One-time setup after creating a repo from this template.
# Replaces the template owner/name everywhere and moves proto/<owner>/.
#   usage: scripts/rename.sh <github-owner> [repo-name]
#   e.g.   scripts/rename.sh my-org my-apis
set -euo pipefail
cd "$(dirname "$0")/.."

OLD_OWNER=longntv
OLD_REPO=grpc-apis-template
NEW_OWNER="${1:?usage: $0 <github-owner> [repo-name]}"
NEW_REPO="${2:-$OLD_REPO}"

# GitHub-style names only; this also keeps sed replacement strings safe.
[[ "$NEW_OWNER" =~ ^[A-Za-z0-9-]+$ ]] || { echo "invalid owner '$NEW_OWNER' (letters, digits, '-')" >&2; exit 1; }
[[ "$NEW_REPO" =~ ^[A-Za-z0-9._-]+$ ]] || { echo "invalid repo name '$NEW_REPO'" >&2; exit 1; }
# Proto package segments must be lower-case letters/digits; npm names lower-case.
NEW_PKG="$(printf '%s' "$NEW_OWNER" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9')"
NEW_NPM_REPO="$(printf '%s' "$NEW_REPO" | tr '[:upper:]' '[:lower:]')"
[[ "$NEW_PKG" =~ ^[a-z][a-z0-9]*$ ]] || { echo "cannot derive a proto package from '$NEW_OWNER'" >&2; exit 1; }
[[ -d "proto/$OLD_OWNER" ]] || { echo "already renamed (proto/$OLD_OWNER not found)" >&2; exit 1; }
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || { echo "run inside the git checkout of the template" >&2; exit 1; }

# Order matters: specific forms first, then the bare proto package / repo name.
#   github.com/longntv/grpc-apis-template -> github.com/<owner>/<repo> (Go module, URLs)
#   @longntv/grpc-apis-template           -> @<pkg>/<repo>             (npm scope)
#   longntv-grpc-apis-template            -> <pkg>-<repo>              (PyPI name)
#   @longntv                              -> @<owner>                  (CODEOWNERS)
#   longntv                               -> <pkg>                     (proto package, paths)
# Only tracked files: never touch build/, dist/, .venv/ or other local artifacts.
git ls-files -z | xargs -0 grep -lI -e "$OLD_OWNER" -e "$OLD_REPO" -- |
  grep -vE '^(gen/|scripts/rename\.sh$|LICENSE$)' |
while IFS= read -r f; do
  sed -i.bak \
    -e "s#github\.com/$OLD_OWNER/$OLD_REPO#github.com/$NEW_OWNER/$NEW_REPO#g" \
    -e "s#github:$OLD_OWNER/$OLD_REPO#github:$NEW_OWNER/$NEW_REPO#g" \
    -e "s#@$OLD_OWNER/$OLD_REPO#@$NEW_PKG/$NEW_NPM_REPO#g" \
    -e "s#$OLD_OWNER-$OLD_REPO#$NEW_PKG-$NEW_NPM_REPO#g" \
    -e "s#@$OLD_OWNER\$#@$NEW_OWNER#g" \
    -e "s#@$OLD_OWNER #@$NEW_OWNER #g" \
    -e "s#$OLD_OWNER#$NEW_PKG#g" \
    -e "s#$OLD_REPO#$NEW_REPO#g" \
    "$f"
  rm -f "$f.bak"
done

git mv "proto/$OLD_OWNER" "proto/$NEW_PKG" 2>/dev/null || mv "proto/$OLD_OWNER" "proto/$NEW_PKG"
# Stale stubs still use the old names; they are regenerated by `make generate`.
rm -rf gen

echo "Renamed to github.com/$NEW_OWNER/$NEW_REPO (proto package: $NEW_PKG.*)."
echo "Next: make init generate && go mod tidy, update LICENSE, then commit."
